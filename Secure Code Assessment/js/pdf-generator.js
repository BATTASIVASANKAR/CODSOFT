/**
 * SECURE CODE ASSESSMENT TOOL - PDF SECURITY REPORT GENERATOR
 * Generates downloadable PDF security assessment reports via html2pdf.js
 */

window.SASTPDFGenerator = (function () {

  function downloadPDF(scanResult) {
    if (!scanResult || !scanResult.findings) {
      alert("No security scan report found. Please run a security scan first.");
      return;
    }

    // Create temporary element for PDF formatting
    const element = document.createElement('div');
    element.id = 'pdf-report-content';
    element.style.padding = '20px';
    element.style.fontFamily = 'Helvetica, Arial, sans-serif';
    element.style.color = '#000';
    element.style.backgroundColor = '#fff';

    const findings = scanResult.findings;
    const metrics = scanResult.metrics;

    let findingsHTML = '';
    findings.forEach((f, idx) => {
      findingsHTML += `
        <div style="margin-bottom: 20px; padding: 12px; border: 1px solid #cbd5e1; border-left: 5px solid ${getSevColor(f.severity)}; border-radius: 6px; page-break-inside: avoid;">
          <div style="display: flex; justify-content: space-between; margin-bottom: 8px;">
            <strong style="font-size: 15px;">#${idx + 1} - ${escapeHTML(f.title)}</strong>
            <span style="background:${getSevColor(f.severity)}; color:#fff; padding: 3px 8px; border-radius: 4px; font-weight: bold; font-size: 11px;">${f.severity}</span>
          </div>
          <p style="margin: 4px 0; font-size: 12px; color: #475569;"><strong>OWASP:</strong> ${escapeHTML(f.owasp || 'Unmapped')} | <strong>Line:</strong> ${f.lineNumber} | <strong>Category:</strong> ${escapeHTML(f.category)}</p>
          <p style="margin: 6px 0; font-size: 12px;"><strong>Description:</strong> ${escapeHTML(f.description)}</p>
          <p style="margin: 6px 0; font-size: 12px;"><strong>Business Risk:</strong> ${escapeHTML(f.risk)}</p>
          <div style="background: #f8fafc; padding: 8px; border-radius: 4px; font-family: monospace; font-size: 11px; color: #991b1b; margin-top: 6px;">
            <strong>Vulnerable Snippet (Line ${f.lineNumber}):</strong><br/>
            ${escapeHTML(f.snippet)}
          </div>
          <p style="margin: 8px 0 4px 0; font-size: 12px; color: #047857;"><strong>Remediation Guidance:</strong> ${escapeHTML(f.remediation)}</p>
          <div style="background: #ecfdf5; padding: 8px; border-radius: 4px; font-family: monospace; font-size: 11px; color: #065f46; margin-top: 4px;">
            <strong>Secure Code Example:</strong><br/>
            <pre style="margin: 0; white-space: pre-wrap;">${escapeHTML(f.secureExample)}</pre>
          </div>
        </div>
      `;
    });

    element.innerHTML = `
      <div style="border-bottom: 2px solid #0284c7; padding-bottom: 15px; margin-bottom: 20px; display: flex; justify-content: space-between; align-items: center;">
        <div>
          <h1 style="margin: 0; color: #0f172a; font-size: 24px;">Secure Code Assessment Report</h1>
          <p style="margin: 4px 0 0 0; color: #64748b; font-size: 13px;">Static Security Review & Vulnerability Assessment</p>
        </div>
        <div style="text-align: right; font-size: 12px; color: #475569;">
          <strong>Date:</strong> ${scanResult.timestamp}<br/>
          <strong>Target:</strong> ${scanResult.filename}<br/>
          <strong>Security Grade:</strong> <span style="font-size: 16px; font-weight: bold; color: ${getScoreColor(metrics.score)};">${metrics.grade} (${metrics.securityScore}/100)</span>
        </div>
      </div>

      <div style="background: #f1f5f9; padding: 15px; border-radius: 8px; margin-bottom: 20px;">
        <h3 style="margin-top: 0; font-size: 16px; color: #0f172a;">Executive Summary</h3>
        <table style="width: 100%; border-collapse: collapse; font-size: 13px;">
          <tr>
            <td><strong>Total Vulnerabilities:</strong> ${metrics.severityCounts.total}</td>
            <td><strong style="color: #ef4444;">Critical:</strong> ${metrics.severityCounts.critical}</td>
            <td><strong style="color: #f97316;">High:</strong> ${metrics.severityCounts.high}</td>
          </tr>
          <tr>
            <td><strong>Total Lines Analyzed:</strong> ${scanResult.totalLines}</td>
            <td><strong style="color: #eab308;">Medium:</strong> ${metrics.severityCounts.medium}</td>
            <td><strong style="color: #3b82f6;">Low:</strong> ${metrics.severityCounts.low}</td>
          </tr>
        </table>
      </div>

      <h3 style="font-size: 16px; color: #0f172a; margin-bottom: 15px;">Detailed Security Findings</h3>
      ${findingsHTML || '<p style="color: #047857;">No vulnerabilities identified in source code.</p>'}

      <div style="margin-top: 30px; border-top: 1px solid #cbd5e1; padding-top: 15px; font-size: 11px; color: #94a3b8; text-align: center;">
        <p>Generated by Secure Code Assessment Tool | Cybersecurity Internship Project</p>
      </div>
    `;

    // Options for html2pdf
    const opt = {
      margin:       10,
      filename:     `Security_Assessment_Report_${scanResult.filename.replace(/\.[^/.]+$/, "")}.pdf`,
      image:        { type: 'jpeg', quality: 0.98 },
      html2canvas:  { scale: 2, logging: false },
      jsPDF:        { unit: 'mm', format: 'a4', orientation: 'portrait' }
    };

    if (window.html2pdf) {
      window.html2pdf().set(opt).from(element).save();
    } else {
      // Fallback if html2pdf CDN is loading: use browser print view
      const printWindow = window.open('', '_blank');
      printWindow.document.write('<html><head><title>Security Assessment Report</title></head><body>' + element.innerHTML + '</body></html>');
      printWindow.document.close();
      printWindow.print();
    }
  }

  function getSevColor(severity) {
    switch (severity.toUpperCase()) {
      case 'CRITICAL': return '#ef4444';
      case 'HIGH': return '#f97316';
      case 'MEDIUM': return '#eab308';
      case 'LOW': return '#3b82f6';
      default: return '#64748b';
    }
  }

  function getScoreColor(score) {
    if (score >= 80) return '#10b981';
    if (score >= 60) return '#eab308';
    return '#ef4444';
  }

  function escapeHTML(str) {
    if (!str) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  return {
    downloadPDF: downloadPDF
  };

})();
